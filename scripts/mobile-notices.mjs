// Lists every package shipped in the NOVA mobile app (production dependency
// tree of apps/mobile) with its licence, for THIRD-PARTY-NOTICES.md.
// Usage: node scripts/mobile-notices.mjs > apps/mobile/THIRD-PARTY-NOTICES.md
import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "../apps/mobile");
const seen = new Map();

function resolve(name, from) {
  let dir = from;
  for (;;) {
    const p = join(dir, "node_modules", name, "package.json");
    if (existsSync(p)) return p;
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

function walk(name, from) {
  const pj = resolve(name, from);
  if (!pj) return;
  const pkg = JSON.parse(readFileSync(pj, "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  const license = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? ((pkg.licenses ?? []).map((l) => l.type ?? l).join(" OR ") || "UNKNOWN"));
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? "";
  seen.set(key, { name: pkg.name, version: pkg.version, license, repo: repo.replace(/^git\+/, "").replace(/\.git$/, "") });
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) walk(dep, dirname(pj));
}

const root = JSON.parse(readFileSync(join(app, "package.json"), "utf8"));
for (const dep of Object.keys(root.dependencies)) {
  if (dep === "react-native-web" || dep === "react-dom") continue; // web preview only, not in the phone app
  walk(dep, app);
}

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const byLicense = new Map();
for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

